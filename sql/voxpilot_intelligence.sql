-- VoxPilot | Step 3: Adoption-to-Revenue Intelligence
-- Synthetic demo; run after Step 2. No existing data is deleted.
USE DATABASE VOXPILOT;
USE SCHEMA ANALYTICS;

-- Anchor the analysis to the last date in the dataset (not today's date).
CREATE OR REPLACE VIEW ACCOUNT_INTELLIGENCE AS
WITH anchor AS (
 SELECT MAX(USAGE_DATE) AS AS_OF_DATE FROM PRODUCT_USAGE
), periods AS (
 SELECT u.CUSTOMER_ID, u.CHANNEL,
   SUM(IFF(u.USAGE_DATE > DATEADD(day,-30,a.AS_OF_DATE),u.CONVERSATIONS,0)) AS CURRENT_CONVERSATIONS,
   SUM(IFF(u.USAGE_DATE BETWEEN DATEADD(day,-59,a.AS_OF_DATE) AND DATEADD(day,-30,a.AS_OF_DATE),u.CONVERSATIONS,0)) AS PRIOR_CONVERSATIONS,
   SUM(IFF(u.USAGE_DATE > DATEADD(day,-30,a.AS_OF_DATE),u.API_ERRORS,0)) AS CURRENT_ERRORS,
   SUM(IFF(u.USAGE_DATE BETWEEN DATEADD(day,-59,a.AS_OF_DATE) AND DATEADD(day,-30,a.AS_OF_DATE),u.API_ERRORS,0)) AS PRIOR_ERRORS,
   SUM(IFF(u.USAGE_DATE > DATEADD(day,-30,a.AS_OF_DATE),u.SUCCESSFUL_CONVERSATIONS,0)) AS CURRENT_SUCCESSES,
   AVG(IFF(u.USAGE_DATE > DATEADD(day,-30,a.AS_OF_DATE),u.AVG_LATENCY_MS,NULL)) AS CURRENT_LATENCY_MS
 FROM PRODUCT_USAGE u CROSS JOIN anchor a
 GROUP BY u.CUSTOMER_ID,u.CHANNEL
), account_metrics AS (
 SELECT CUSTOMER_ID,
   SUM(CURRENT_CONVERSATIONS) AS CURRENT_30D_CONVERSATIONS,
   SUM(PRIOR_CONVERSATIONS) AS PRIOR_30D_CONVERSATIONS,
   ROUND(100.0*(SUM(CURRENT_CONVERSATIONS)-SUM(PRIOR_CONVERSATIONS))/NULLIF(SUM(PRIOR_CONVERSATIONS),0),1) AS USAGE_CHANGE_PCT,
   ROUND(100.0*SUM(CURRENT_ERRORS)/NULLIF(SUM(CURRENT_CONVERSATIONS),0),2) AS ERROR_RATE_PCT,
   ROUND(100.0*SUM(PRIOR_ERRORS)/NULLIF(SUM(PRIOR_CONVERSATIONS),0),2) AS PRIOR_ERROR_RATE_PCT,
   ROUND(100.0*SUM(CURRENT_SUCCESSES)/NULLIF(SUM(CURRENT_CONVERSATIONS),0),1) AS SUCCESS_RATE_PCT,
   ROUND(SUM(CURRENT_LATENCY_MS*CURRENT_CONVERSATIONS)/NULLIF(SUM(CURRENT_CONVERSATIONS),0)) AS AVG_LATENCY_MS,
   COUNT_IF(CURRENT_CONVERSATIONS>0) AS ACTIVE_CHANNELS
 FROM periods GROUP BY CUSTOMER_ID
), enriched AS (
 SELECT c.CUSTOMER_ID,c.CUSTOMER_NAME,c.INDUSTRY,c.ARR,c.RENEWAL_DATE,
   DATEDIFF(day,a.AS_OF_DATE,c.RENEWAL_DATE) AS DAYS_TO_RENEWAL,
   c.CONTRACTED_MONTHLY_CAPACITY,c.DEPLOYED_CHANNELS,
   m.CURRENT_30D_CONVERSATIONS,m.PRIOR_30D_CONVERSATIONS,m.USAGE_CHANGE_PCT,
   m.ERROR_RATE_PCT,m.PRIOR_ERROR_RATE_PCT,m.SUCCESS_RATE_PCT,m.AVG_LATENCY_MS,m.ACTIVE_CHANNELS,
   ROUND(100.0*m.CURRENT_30D_CONVERSATIONS/NULLIF(c.CONTRACTED_MONTHLY_CAPACITY,0),1) AS CAPACITY_UTILISATION_PCT
 FROM CUSTOMERS c JOIN account_metrics m ON c.CUSTOMER_ID=m.CUSTOMER_ID CROSS JOIN anchor a
), classified AS (
 SELECT e.*,
   IFF(USAGE_CHANGE_PCT<=-20,1,0) AS USAGE_DECLINE_FLAG,
   IFF(ERROR_RATE_PCT>=5 OR ERROR_RATE_PCT-PRIOR_ERROR_RATE_PCT>=3,1,0) AS ERROR_FLAG,
   IFF(SUCCESS_RATE_PCT<75,1,0) AS LOW_SUCCESS_FLAG,
   IFF(DAYS_TO_RENEWAL BETWEEN 0 AND 90,1,0) AS NEAR_RENEWAL_FLAG,
   IFF(USAGE_CHANGE_PCT>=20 AND SUCCESS_RATE_PCT>=85 AND ERROR_RATE_PCT<3,1,0) AS HEALTHY_GROWTH_FLAG
 FROM enriched e
)
SELECT *,
 CASE WHEN USAGE_DECLINE_FLAG+ERROR_FLAG+LOW_SUCCESS_FLAG>=2 THEN 'HIGH RISK'
      WHEN USAGE_DECLINE_FLAG+ERROR_FLAG+LOW_SUCCESS_FLAG=1 THEN 'WATCH'
      ELSE 'HEALTHY' END AS HEALTH_STATUS,
 CASE WHEN ERROR_FLAG=1 THEN 'Investigate integration errors and latency with engineering'
      WHEN LOW_SUCCESS_FLAG=1 THEN 'Review agent conversations and goal failures'
      WHEN USAGE_DECLINE_FLAG=1 THEN 'Run adoption review by channel and identify blockers'
      WHEN HEALTHY_GROWTH_FLAG=1 THEN 'Qualify new use case and consumption expansion'
      ELSE 'Continue monitoring and enablement' END AS NEXT_BEST_ACTION,
 CASE WHEN USAGE_DECLINE_FLAG+ERROR_FLAG+LOW_SUCCESS_FLAG>=1 THEN 'RETENTION'
      WHEN HEALTHY_GROWTH_FLAG=1 THEN 'EXPANSION'
      ELSE 'MONITOR' END AS COMMERCIAL_MOTION,
 IFF(USAGE_DECLINE_FLAG+ERROR_FLAG+LOW_SUCCESS_FLAG>=1,ARR,0) AS ARR_EXPOSED_TO_RISK,
 -- Illustrative sizing assumption: 20% of ARR; NOT an actual quote or forecast.
 IFF(HEALTHY_GROWTH_FLAG=1 AND USAGE_DECLINE_FLAG+ERROR_FLAG+LOW_SUCCESS_FLAG=0,ROUND(ARR*0.20,0),0) AS ILLUSTRATIVE_EXPANSION_ARR
FROM classified;

-- Output 1: ranked account action queue
SELECT CUSTOMER_NAME,ARR,DAYS_TO_RENEWAL,USAGE_CHANGE_PCT,ERROR_RATE_PCT,
 SUCCESS_RATE_PCT,HEALTH_STATUS,COMMERCIAL_MOTION,NEXT_BEST_ACTION,
 ARR_EXPOSED_TO_RISK,ILLUSTRATIVE_EXPANSION_ARR
FROM ACCOUNT_INTELLIGENCE
ORDER BY CASE HEALTH_STATUS WHEN 'HIGH RISK' THEN 0 WHEN 'WATCH' THEN 1 ELSE 2 END,
 NEAR_RENEWAL_FLAG DESC, ARR DESC;

-- Output 2: portfolio summary (potential is not booked revenue)
SELECT COUNT(*) AS ACCOUNTS,SUM(ARR) AS PORTFOLIO_ARR,
 COUNT_IF(HEALTH_STATUS='HIGH RISK') AS HIGH_RISK_ACCOUNTS,
 SUM(ARR_EXPOSED_TO_RISK) AS ARR_EXPOSED_TO_RISK,
 COUNT_IF(COMMERCIAL_MOTION='EXPANSION') AS EXPANSION_CANDIDATES,
 SUM(ILLUSTRATIVE_EXPANSION_ARR) AS ILLUSTRATIVE_EXPANSION_POTENTIAL
FROM ACCOUNT_INTELLIGENCE;

-- Output 3: channel adoption changes
WITH a AS (SELECT MAX(USAGE_DATE) AS AS_OF_DATE FROM PRODUCT_USAGE)
SELECT u.CHANNEL,
 SUM(IFF(u.USAGE_DATE>DATEADD(day,-30,a.AS_OF_DATE),u.CONVERSATIONS,0)) AS CURRENT_30D,
 SUM(IFF(u.USAGE_DATE BETWEEN DATEADD(day,-59,a.AS_OF_DATE) AND DATEADD(day,-30,a.AS_OF_DATE),u.CONVERSATIONS,0)) AS PRIOR_30D,
 ROUND(100.0*(CURRENT_30D-PRIOR_30D)/NULLIF(PRIOR_30D,0),1) AS CHANGE_PCT
FROM PRODUCT_USAGE u CROSS JOIN a
GROUP BY u.CHANNEL;

-- Output 4: historical action log; do not infer causality from this data
SELECT c.CUSTOMER_NAME,a.ACTION_DATE,a.ACTION_TYPE,a.STATUS,a.RECOMMENDATION,a.OUTCOME,a.REVENUE_IMPACT
FROM ACCOUNT_ACTIONS a JOIN CUSTOMERS c ON a.CUSTOMER_ID=c.CUSTOMER_ID
ORDER BY a.ACTION_DATE DESC;
SHOW VIEWS LIKE 'ACCOUNT_INTELLIGENCE'
IN SCHEMA VOXPILOT.ANALYTICS;
SELECT
    CUSTOMER_NAME,
    ARR,
    HEALTH_STATUS,
    USAGE_CHANGE_PCT,
    ERROR_RATE_PCT,
    NEXT_BEST_ACTION
FROM VOXPILOT.ANALYTICS.ACCOUNT_INTELLIGENCE
ORDER BY ARR DESC;
